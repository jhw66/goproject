package main

import (
	"fmt"
	"sync"
)

// 在 Go 1.22 的 官方发布说明
//  中写道：
// For-range loop variables are now per-iteration copies.
// Each iteration now creates a new variable, so that closures capture the correct value.
// 翻译过来：
// for 循环的变量现在是每次迭代的副本，因此闭包会捕获到正确的值。

var wg sync.WaitGroup //只定义不需要赋值
func main() {
	//可以在知道协程次数情况下直接wg.Add(5)
	for i := 1; i <= 5; i++ {
		wg.Add(1) //协程开始的时候加一操作
		fmt.Printf("启动协程%d\n", i)
		//使用匿名函数，直接启动协程
		go func(n int) {
			defer wg.Done() //协程结束的时候减一
			fmt.Println(n)
		}(i) //传递参数，避免闭包陷阱
	}
	//Wait方法堵塞直到WaitGroup计时器减为0
	wg.Wait()
}

// 闭包捕获原理
// 闭包是指一个函数“捕获”了它外层作用域中的变量引用，而不是变量的值。
// 循环变量 i 是在 同一个内存地址 中反复被修改的；
// 每次循环，func() { fmt.Println(i) } 只是捕获了这个 同一个变量的引用；
// 循环结束时，i 变成了 3；
// 所以所有的闭包在运行时看到的都是 i == 3。
// 换句话说：
// Go 的闭包是“引用捕获”（by reference），而不是“值捕获”（by value）。
// 如何修复:
// 解决方法是让每次循环创建一个新的局部变量副本，例如：
// for i := 0; i < 3; i++ {
//     j := i // 创建一个新的局部变量
//     funcs = append(funcs, func() {
//         fmt.Println(j)
//     })
// }
// ✅ 原理：
// j 每次循环都会被重新创建、重新分配内存，因此每个闭包捕获的是不同的变量。

// // 版本1：值传递
// go func(n int) {
//     // n是i的副本，每个goroutine有自己的n
//     fmt.Println(n)  // 打印的是创建时的i值
// }(i)  // i的值被复制

// // 版本2：闭包引用
// go func() {
//     // 引用的是同一个i变量（内存地址）
//     fmt.Println(i)  // 打印的是i当前的值
// }()  // 没有传递参数
// 第一个代码片段（传递参数）：
// 每个协程启动时，都会将当前的i值复制一份传给匿名函数，所以每个协程打印的是自己接收到的参数值，分别是1,2,3,4,5。
// 但是由于协程启动的顺序和执行的顺序不确定，打印的顺序可能是乱序的，但是打印的值是1到5这5个数字。

// 第二个代码片段（闭包，没有传递参数）：
// 匿名函数内部引用了外部变量i，这个i是循环变量，在循环中不断变化。当协程开始执行时，它们打印的是当前i的值。
// 由于协程的启动和执行有延迟，可能当协程执行fmt.Println(i)时，循环已经结束，此时i的值已经变成了6（当i=6时跳出循环）。
// 所以，所有协程可能都打印6，或者打印其他值（取决于协程启动的时刻）。但通常，我们会看到打印多个6，因为循环很快就结束了，
// 协程在循环结束后才开始执行。
